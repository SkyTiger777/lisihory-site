// Downloads the subset fonts used by the site and writes assets/fonts/fonts.css
import { mkdir, writeFile } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import path from "node:path";

const OUT = path.resolve("assets/fonts");
await mkdir(OUT, { recursive: true });

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36";

const families = [
  { css: "Onest:wght@300;400;500;600", name: "Onest", keep: ["cyrillic", "latin"] },
  {
    css: "Cormorant+Garamond:ital,wght@1,300;1,400",
    name: "Cormorant Garamond",
    keep: ["cyrillic", "latin"],
  },
];

const url = `https://fonts.googleapis.com/css2?${families
  .map((f) => `family=${f.css}`)
  .join("&")}&display=swap`;

const css = await (
  await fetch(url, { headers: { "User-Agent": UA } })
).text();

const blocks = css.split("/*").slice(1);
const faces = [];
let index = 0;

for (const block of blocks) {
  const subset = block.slice(0, block.indexOf("*/")).trim();
  const body = block.slice(block.indexOf("*/") + 2);
  const family = /font-family: '([^']+)'/.exec(body)?.[1];
  const weight = /font-weight: (\d+)/.exec(body)?.[1];
  const style = /font-style: (\w+)/.exec(body)?.[1];
  const src = /src: url\(([^)]+)\)/.exec(body)?.[1];
  const range = /unicode-range: ([^;]+);/.exec(body)?.[1];
  const spec = families.find((f) => f.name === family);
  if (!spec || !src || !spec.keep.includes(subset)) continue;

  const ext = ".woff2";
  const file = `${spec.name.toLowerCase().replace(/\s+/g, "-")}-${weight}-${style}-${subset}${ext}`;
  const res = await fetch(src, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Font download failed: ${src}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(path.join(OUT, file), buf);
  console.log(`${file} ${(buf.length / 1024).toFixed(1)} kB`);
  faces.push({ family, weight, style, file, range, subset });
  index++;
}

const order = { cyrillic: 0, latin: 1 };
faces.sort(
  (a, b) =>
    families.findIndex((f) => f.name === a.family) -
      families.findIndex((f) => f.name === b.family) ||
    Number(a.weight) - Number(b.weight) ||
    order[a.subset] - order[b.subset],
);

const fontCss =
  "/* Self-hosted fonts. Generated by scripts/fonts.mjs — do not edit by hand. */\n" +
  faces
    .map(
      (f) => `@font-face {
  font-family: '${f.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url('./${f.file}') format('woff2');
  unicode-range: ${f.range};
}`,
    )
    .join("\n\n") +
  "\n";

await writeFile(path.join(OUT, "fonts.css"), fontCss);
console.log("fonts.css written");
